export type Key = keyof typeof es
export type Lang = 'es' | 'en'
let dict: typeof es = navigator.language.toLowerCase().startsWith('es') ? es : en

export function setLang(lang: Lang) {
  dict = lang === 'es' ? es : en
}

/** Dates and numbers in the interface language */
export const locale = () => (dict === es ? 'es-ES' : 'en-GB')

export function t(key: Key, vars: Record<string, string | number> = {}) {
  return dict[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}

/** A count: the key's "_one" form when N is 1 and there is one */
export function tn(key: Key, n: number, vars: Record<string, string | number> = {}) {
  const one = `${key}_one` as Key
  return t(n === 1 && one in dict ? one : key, { n, ...vars })
}

export function bytes(n: number) {
  if (!n) return '0 B'
  const u = ['B', 'KB', 'MB', 'GB', 'TB']
  const i = Math.min(u.length - 1, Math.floor(Math.log(n) / Math.log(1024)))
  return `${(n / 1024 ** i).toFixed(i ? 1 : 0)} ${u[i]}`
}
